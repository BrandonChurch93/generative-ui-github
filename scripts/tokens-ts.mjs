import { readFileSync, writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const css = readFileSync(resolve(root, 'design-system/tokens.css'), 'utf8')
const out = resolve(root, 'packages/ui/src/tokens.ts')

const names = [...new Set([...css.matchAll(/--([a-z0-9-]+)\s*:/g)].map(m => m[1]))]

const body = `// Generated by scripts/tokens-ts.mjs from design-system/tokens.css. Run pnpm tokens:build instead of editing.
export const TOKEN_NAMES = [
${names.map(n => `  '${n}',`).join('\n')}
] as const

export type TokenName = (typeof TOKEN_NAMES)[number]

export function cssVar<N extends TokenName>(name: N): \`var(--\${N})\` {
  return \`var(--\${name})\`
}
`
writeFileSync(out, body)
console.log(`wrote ${out} (${names.length} tokens)`)
